import { randomUUID } from 'node:crypto'

/** Схема ключей в бакете (SRS §5.5).
 *
 *  Сырые байты и итоговое изображение адресуются по-разному, и это не украшение:
 *  до нормализации содержимое ещё не определяет байты, поэтому контент-адресация
 *  к `incoming/` неприменима, а после — обязательна. */

/** Сырой объект живёт минуты: воркер удаляет его сам, забытые подчищает
 *  lifecycle-правило бакета «старше суток» — одна строка конфигурации вместо
 *  сборщика мусора в коде. */
export function incomingKey(): string {
  return `incoming/${randomUUID()}`
}

/** Двухсимвольный префикс разбрасывает объекты по 256 «папкам»: листинг бакета
 *  и веб-консоль остаются пригодными к использованию при десятках тысяч объектов.
 *
 *  Ключ **не содержит** `report_id`: одно и то же фото, прилетевшее дважды на разные
 *  заявки, хранилось бы дважды. Связь «фото ↔ заявка» живёт в БД — единственном месте,
 *  где она нужна. Побочный эффект — дедупликация: повторная загрузка того же файла
 *  это идемпотентный PUT по тому же ключу. */
export function photoKey(sha256: string): string {
  return `photos/${sha256.slice(0, 2)}/${sha256}.jpg`
}

export function previewKey(sha256: string): string {
  return `photos/${sha256.slice(0, 2)}/${sha256}_400.jpg`
}
