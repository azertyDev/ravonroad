import { randomBytes } from 'node:crypto'

/** 16 байт — 128 бит энтропии, пространство 3,4 × 10³⁸. При 10⁴ выданных токенах
 *  и лимите 30 запросов/мин с адреса ожидаемое время до первого угадывания превышает
 *  возраст Вселенной на много порядков. 64 бита понижать нельзя: там уже считается. */
const TOKEN_BYTES = 16

/** `base64url` даёт 22 символа против 32 у base32. Токен копируется кнопкой, а не
 *  набирается руками (US-012), поэтому «неоднозначные символы» роли не играют,
 *  а URL-безопасность важна: токен лежит в пути. */
export const TRACKING_TOKEN_LENGTH = 22

/** Источник — CSPRNG `node:crypto`. `Math.random()` запрещён явно: он предсказуем
 *  по нескольким выходам, а токен — единственная capability в системе (SRS §2.3).
 *
 *  Токен **не выводится** из `public_number`: ни хешем, ни HMAC, ни «номер + соль».
 *  Любая функция от публичного номера превращает его в ключ доступа ко всем заявкам
 *  сразу — это и есть IDOR (SRS §9.2). */
export function generateTrackingToken(): string {
  return randomBytes(TOKEN_BYTES).toString('base64url')
}
