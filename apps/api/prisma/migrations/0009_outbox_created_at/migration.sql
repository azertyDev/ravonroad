-- 006 — возраст неотправленной записи очереди доставки (SRS §10.4).
--
-- Алерт «старейшая неотправленная запись outbox старше 10 минут» без этой колонки
-- неизмерим: единственная временная отметка строки — `next_attempt_at`, и backoff
-- двигает её вперёд на каждой неудаче. То есть чем дольше длится сбой, тем «моложе»
-- выглядела бы очередь — ровно наоборот тому, ради чего условие написано.
--
-- Откат: DROP COLUMN. Колонка со значением по умолчанию обратно совместима — код
-- предыдущей версии её не читает и не пишет.
ALTER TABLE telegram_outbox
    ADD COLUMN created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now();
