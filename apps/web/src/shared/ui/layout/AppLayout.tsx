import type { ReactNode } from 'react'
import { AppFooter } from './AppFooter'
import { AppHeader } from './AppHeader'

/** Каркас страницы. Ширина содержимого ограничена; проектируем от 360 px,
 *  где горизонтальная прокрутка недопустима (PRD §8.3).
 *
 *  Горизонтальное поле держит не каркас, а сами блоки. В плакатном ключе счётчик,
 *  статусное поле и полосы фотографий идут во всю ширину экрана, и общий padding
 *  на `main` не дал бы им выйти за поля. Обычный блок берёт поле классом `GUTTER`.
 *
 *  Подвал стоит после `main`, а нижняя панель действия — внутри него: `sticky`
 *  перестаёт держать панель на дне своего контейнера, поэтому она никогда не
 *  накрывает подвал и не требует под себя постоянного отступа.
 *
 *  На ноутбуке экран занимает окно целиком: ни поля вокруг, ни рамки, ни потолка
 *  ширины. Макет Desktop C рисует карточку 1440 с полем по кромке — от неё отказались
 *  намеренно: поле съедало полосу карты, ради которой экран и сделан, а на широком
 *  мониторе карточка оставляла тёмную раму вокруг работающего интерфейса.
 *  Лента остаётся кромкой самой страницы.
 *
 *  Высота равна окну, и прокручивается не страница, а `main` внутри неё:
 *  шапка с действием и подвал обязаны остаться на месте, а карта — заполнить остаток
 *  высоты. Отсюда же `min-h-0` — без него содержимое флекс-колонки не даёт ей сжаться
 *  до заданной высоты, и прокрутка уезжает на всю страницу вместе с шапкой. */
export function AppLayout({ children }: { children: ReactNode }) {
  return (
    <div className="flex min-h-dvh w-full flex-col overflow-hidden lg:h-dvh lg:min-h-0">
      {/* Предупреждающая лента — кромка страницы. Одна из двух текстур системы,
          и обе служебные: на карте не появляется ни та, ни другая. */}
      <div aria-hidden="true" className="h-[8px] shrink-0 bg-[image:var(--hazard-tape)]" />
      <AppHeader />
      <main className="mx-auto flex w-full max-w-[720px] flex-1 flex-col pt-[var(--s-4)] lg:max-w-none lg:min-h-0 lg:overflow-auto lg:pt-0">
        {children}
      </main>
      <AppFooter />
    </div>
  )
}
