import { formatNumber } from '../../shared/format/number'

export interface CampaignScale {
  /** Доля выполнения, 0…1. Из неё считается и подпись, и заполнение шкалы. */
  share: number
  /** Значение `right` для заливки шкалы: доля 34,7% — это правый отступ 65,3%.
   *  Не `width`: запись через `inset` на этом регулярно спотыкается. */
  right: string
  /** Цифры одометра, по одной на ячейку. Разделители разрядов выброшены — их рисует
   *  сама раскладка ячеек, — но берутся они из того же `formatNumber`, что и число
   *  для скринридера. */
  digits: string[]
}

/** Все числа счётчика из одной пары значений.
 *
 *  Собраны в одну функцию не ради красоты: цифры над шкалой и заливка под ними обязаны
 *  идти от одного числа. Разъехавшись, шкала не падает — она молча врёт, а это главный
 *  числовой блок сайта, и расхождение читается как обман. Пока обе величины считаются
 *  здесь, разъехаться им негде. */
export function campaignScale(done: number, goal: number): CampaignScale {
  // Доля зажата сверху: перевыполненная кампания рисует полную шкалу, а не вылезает
  // за неё. Нулевая или отрицательная цель — деление, которого не должно случиться,
  // но приходит оно с сервера, а не из кода.
  const share = goal <= 0 ? 0 : Math.min(Math.max(done / goal, 0), 1)

  return {
    share,
    // До десятой — до той же, что показывает подпись рядом: 34,7% и 65,3% обязаны
    // быть дополнением друг друга, а не 34,7% и 65,28999999999999%. Разница
    // в сотую процента — это 0,035 px на шкале шириной 350.
    right: `${+(100 - share * 100).toFixed(1)}%`,
    digits: formatNumber(done).replace(/\D/g, '').split(''),
  }
}
