/** Счётчик кампании (SRS §4.6, PRD 5.3.2). Все числа считаются из данных, а не хранятся
 *  полями, которые рано или поздно разойдутся с заявками: «отремонтировано» обязано
 *  оставаться правдой без сверок.
 *
 *  Числа плаката на главной берутся отсюда же — отдельного запроса у них нет, весь набор
 *  считается одним проходом по тому же снимку, из которого рисуется карта (SRS §4.7).
 *
 *  Числа бригад в контракте нет намеренно: такой сущности в системе не существует,
 *  а печатать выдуманное число на публичном сайте кампании нельзя. */
export interface StatsResponse {
  done: number
  goal: number
  /** Прибавка за последние семь суток — скользящее окно, а не календарная неделя:
   *  в понедельник утром цифра не должна обнуляться. */
  doneLastWeek: number
  /** Заявки в статусе `NEW`: те, которых ещё не касался модератор. `ACCEPTED`
   *  и `IN_PROGRESS` уже разобраны и в очереди не стоят. */
  queued: number
  /** Районов, где есть хотя бы одна публичная заявка. */
  districts: number
}

