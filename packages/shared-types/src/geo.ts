/** Типы результатов сырых запросов к PostGIS (SRS §2.14, ADR-0003).
 *
 *  Геометрия недоступна Prisma Client, поэтому два запроса — определение района
 *  и поиск дублей — идут через `$queryRaw`, а типизация их результата ручная.
 *  Она объявлена здесь, а не рядом с запросом, потому что это и есть контракт
 *  между SQL и кодом: разъехавшись, он ломает не типизацию, а данные заявки. */

/** Строка ответа point-in-polygon: район, в чей полигон попала точка (SRS §3.3).
 *  Пустой результат означает «вне города» — это и есть геозабор. */
export interface DistrictCodeRow {
  code: string
}

/** Кандидат в дубли: заявка в 50 м от новой точки (SRS §3.2). `duplicate_candidate_of_id`
 *  нужен, чтобы новая заявка цеплялась к корню кластера, а не к его ветке. Имена колонок —
 *  как в БД: строку отдаёт `$queryRaw`, и переименование здесь означало бы `AS` в SQL. */
export interface DuplicateCandidateRow {
  id: number
  duplicate_candidate_of_id: number | null
}
